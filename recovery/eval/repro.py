"""The clean-clone reproduction gate.

The submission's strongest claim is *clone this, run one command, get the published
number*. This module is the thing that either backs that claim or refuses to.

It re-derives every committed artifact from the seed and **byte-compares** against
what is on disk:

1. the cohort file, including its line count,
2. one ledger per arm named in the run manifest,
3. the hash chain over each of those ledgers.

**Why the line count is checked separately.** ``WHAT_BROKE.md`` incident 2 records a
development run that silently truncated the committed 500-case cohort to 20 cases. The
truncated file was a strict *prefix* of the real one -- same generator, same seed,
byte-identical rows -- so a gate that regenerated ``n`` cases from the file's own
length and compared them would have found them identical and reported a clean
reproduction of a cohort nobody published a number for. The authority for ``n`` is
therefore the run manifest, never the cohort file's own length.

Exit status is 0 only if every check passes. A reproduction gate that reports success
on a partial match is worse than no gate at all.
"""

from __future__ import annotations

import os
import shutil
import subprocess
import sys
import tempfile
from dataclasses import dataclass
from pathlib import Path

from recovery.eval import harness

DEFAULT_RESULTS_ROOT = Path("data/results")
ROOT = Path(__file__).resolve().parent.parent.parent

# Credentials are stripped from the child environment rather than merely left unset, so
# the gate proves the published numbers need none even on a machine that has them.
BLOCKED_ENV = ("ANTHROPIC_API_KEY", "RAZORPAY_KEY_ID", "RAZORPAY_KEY_SECRET")


@dataclass(frozen=True)
class Check:
    name: str
    passed: bool
    detail: str

    def line(self) -> str:
        return f"  [{'PASS' if self.passed else 'FAIL'}] {self.name:<38} {self.detail}"


def _compare_bytes(name: str, regenerated: Path, committed: Path) -> Check:
    if not committed.exists():
        return Check(name, False, f"{committed} is missing")
    a, b = regenerated.read_bytes(), committed.read_bytes()
    if a == b:
        return Check(name, True, f"{len(b):,} bytes identical")
    return Check(name, False, f"{len(a):,} regenerated bytes != {len(b):,} committed bytes")


def check_cohort(seed: int, n: int, cohort_path: Path, workdir: Path) -> list[Check]:
    """Regenerate the cohort and compare it, including its length, against the file."""
    from recovery import cohort as cohort_mod

    checks: list[Check] = []
    if not cohort_path.exists():
        return [Check("cohort artifact present", False, f"{cohort_path} is missing")]

    committed_lines = cohort_path.read_text(encoding="utf-8").strip().splitlines()
    checks.append(
        Check(
            "cohort has the manifest's case count",
            len(committed_lines) == n,
            f"{len(committed_lines):,} lines, manifest says {n:,}",
        )
    )

    regenerated = workdir / cohort_path.name
    cohort_mod.write_cohort(cohort_mod.generate_cohort(seed=seed, n=n), regenerated)
    checks.append(_compare_bytes("cohort reproduces from the seed", regenerated, cohort_path))
    return checks


def check_run(run_dir: Path, workdir: Path) -> list[Check]:
    """Re-run every arm in the manifest and byte-compare its ledger.

    The run id is deliberately reused: it appears in every ledger entry, so a re-run
    under a different id would differ in every line and the comparison would be
    meaningless. Only the output root changes.
    """
    run = harness.load_run(run_dir)
    arms = [a.arm for a in run.arms]
    if not arms:
        return [Check("run has arms to reproduce", False, f"no arm ledgers under {run_dir}")]

    harness.run(
        seed=run.seed,
        n=run.n,
        arms=arms,
        params=run.params,
        out_root=workdir,
        run_id=run.run_id,
    )

    checks = [
        _compare_bytes(
            f"{arm} ledger reproduces", workdir / run.run_id / f"{arm}.jsonl", run_dir / f"{arm}.jsonl"
        )
        for arm in arms
    ]
    checks.extend(
        Check(f"{arm} hash chain verifies", ok, "append-only chain intact" if ok else "CHAIN BROKEN")
        for arm, ok in harness.verify_run(run).items()
    )
    return checks


# -- the clean-clone gate -------------------------------------------------------------


def _sh(cmd: list[str], cwd: Path) -> tuple[int, str]:
    """Run a child process with the credentials stripped out of its environment."""
    env = {k: v for k, v in os.environ.items() if k not in BLOCKED_ENV}
    env["PIP_DISABLE_PIP_VERSION_CHECK"] = "1"
    proc = subprocess.run(
        cmd, cwd=cwd, env=env, capture_output=True, text=True, errors="replace"
    )
    return proc.returncode, (proc.stdout or "") + (proc.stderr or "")


def _materialise(dest: Path, *, worktree: bool) -> tuple[bool, str]:
    """Put a copy of the project at ``dest``.

    The default clones ``HEAD``, which is the honest question -- *can a stranger clone
    this repository and get the number?* -- and therefore fails when the work that
    produces the number is still uncommitted. ``worktree`` copies the files git would
    include instead, which answers the weaker question of whether the working tree is
    self-sufficient. Both create a fresh virtualenv; only the source differs.
    """
    if not worktree:
        code, out = _sh(["git", "clone", "--local", "--no-hardlinks", str(ROOT), str(dest)], ROOT)
        return code == 0, "cloned HEAD" if code == 0 else out.strip().splitlines()[-1][:120]

    code, out = _sh(["git", "ls-files", "--cached", "--others", "--exclude-standard"], ROOT)
    if code != 0:
        return False, out.strip()[:120]
    names = [n for n in out.splitlines() if n.strip()]
    for name in names:
        src = ROOT / name
        if not src.is_file():
            continue
        target = dest / name
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src, target)
    return True, f"copied {len(names):,} tracked and untracked files"


def clean_clone(
    run_id: str | None = None,
    results_root: Path | str = DEFAULT_RESULTS_ROOT,
    *,
    worktree: bool = False,
) -> int:
    """Clone, build a fresh virtualenv, install, run, and byte-compare the artifacts.

    **The fresh virtualenv is the point.** Re-deriving the numbers inside the
    development environment -- which :func:`main` does, quickly -- cannot tell you that
    ``pyproject.toml`` declares everything the project needs, because every dependency
    is already importable there. A reviewer cloning the repository would hit the
    ``ImportError`` this gate exists to hit first.
    """
    from recovery.eval.report import resolve_run_dir

    run_dir = resolve_run_dir(run_id, results_root)
    run = harness.load_run(run_dir)
    arms = [a.arm for a in run.arms]

    print()
    print(f"clean-clone reproduction gate: {run_dir}")
    print(f"seed {run.seed}, {run.n} cases, arms {', '.join(arms)}")
    print(f"source: {'working tree' if worktree else 'git HEAD'}")
    print("credentials stripped from the child environment: " + ", ".join(BLOCKED_ENV))
    print()

    checks: list[Check] = []
    with tempfile.TemporaryDirectory(prefix="recovery-clean-") as tmp:
        clone = Path(tmp) / "clone"
        clone.mkdir(parents=True)

        ok, detail = _materialise(clone, worktree=worktree)
        checks.append(Check("project materialises into a temp dir", ok, detail))
        if not ok:
            return _verdict(checks)

        print("  building a fresh virtualenv and installing... (this is the slow part)")
        code, out = _sh([sys.executable, "-m", "venv", ".venv"], clone)
        checks.append(
            Check("fresh virtualenv created", code == 0, ".venv" if code == 0 else out[-120:])
        )
        if code != 0:
            return _verdict(checks)

        py = clone / ".venv" / ("Scripts" if os.name == "nt" else "bin") / (
            "python.exe" if os.name == "nt" else "python"
        )
        code, out = _sh([str(py), "-m", "pip", "install", "-e", ".", "-q"], clone)
        checks.append(
            Check(
                "pyproject declares every dependency",
                code == 0,
                "installed from pyproject alone" if code == 0 else out.strip()[-160:],
            )
        )
        if code != 0:
            return _verdict(checks)

        code, out = _sh(
            [str(py), "-m", "recovery.cli", "eval", "--seed", str(run.seed),
             "--n", str(run.n), "--arms", ",".join(arms)],
            clone,
        )
        checks.append(
            Check(
                "eval runs with no credentials present",
                code == 0,
                "completed offline" if code == 0 else out.strip()[-160:],
            )
        )
        if code != 0:
            return _verdict(checks)

        cohort_name = f"cohort_seed{run.seed}.jsonl"
        checks.append(
            _compare_bytes(
                "cohort matches the committed artifact",
                clone / "data" / cohort_name,
                ROOT / "data" / cohort_name,
            )
        )
        for arm in arms:
            checks.append(
                _compare_bytes(
                    f"{arm} ledger matches the committed artifact",
                    clone / "data" / "results" / run.run_id / f"{arm}.jsonl",
                    run_dir / f"{arm}.jsonl",
                )
            )

    return _verdict(checks)


def _verdict(checks: list[Check]) -> int:
    for check in checks:
        print(check.line())
    failed = [c for c in checks if not c.passed]
    print()
    if failed:
        print(f"REPRODUCTION FAILED: {len(failed)} of {len(checks)} checks did not pass.")
        print("A reviewer cloning this repository would not get the published numbers.")
        return 1
    print(f"reproduced: all {len(checks)} checks passed, from a clean tree and a fresh venv.")
    return 0


def main(
    run_id: str | None = None,
    results_root: Path | str = DEFAULT_RESULTS_ROOT,
    cohort_path: Path | str | None = None,
) -> int:
    """Reproduce every committed artifact from the seed. Returns 0 only if all match."""
    from recovery.eval.report import resolve_run_dir

    run_dir = resolve_run_dir(run_id, results_root)
    run = harness.load_run(run_dir)
    cohort_file = (
        Path(cohort_path) if cohort_path else Path(f"data/cohort_seed{run.seed}.jsonl")
    )

    print()
    print(f"reproduction gate: {run_dir}")
    print(f"seed {run.seed}, {run.n} cases, arms {', '.join(a.arm for a in run.arms)}")
    print()

    with tempfile.TemporaryDirectory(prefix="recovery-repro-") as tmp:
        workdir = Path(tmp)
        checks = check_cohort(run.seed, run.n, cohort_file, workdir)
        checks += check_run(run_dir, workdir)

    for check in checks:
        print(check.line())

    failed = [c for c in checks if not c.passed]
    print()
    if failed:
        print(f"REPRODUCTION FAILED: {len(failed)} of {len(checks)} checks did not pass.")
        print("The committed artifacts and the code that claims to produce them disagree.")
        return 1
    print(f"reproduced: all {len(checks)} checks passed. The published numbers are the code's.")
    return 0
